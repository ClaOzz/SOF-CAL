const assert=require('node:assert/strict');
const P=require('../fuentes/protocol-model45.js');
const m=P.create('sat-scadi',{system:'SCADI',location:'E04'});
assert.deepEqual(m.answers,{});
P.add(m,'sessions','s1',{date:'2026-11-12'});
P.add(m,'sessions','s2',{date:'2026-11-13'});
assert.equal(m.sessions.length,2);
assert.throws(()=>P.add(m,'sessions','s1'),/duplicado/);
P.answer(m,'p1','PEND','Prueba no ejecutada');
m.pending[0].responsible='Inspector';
P.answer(m,'p1','PEND','Falta instrumento');
assert.equal(m.pending.length,1);
assert.equal(m.pending[0].responsible,'Inspector');
P.answer(m,'p2','NOK','Valor fuera del criterio');
assert.equal(m.pending.length,2);
assert.deepEqual(P.totals(m,['p1','p2','p3']),{OK:0,NOK:1,PEND:1,'N/A':0,unanswered:1,total:3});
P.answer(m,'p1','OK');assert.equal(m.pending.length,1);
P.answer(m,'p3','N/A','Equipo no incluido en esta ubicación');
assert.equal(P.validate(m,['p1','p2','p3']).length,0);
assert.equal(P.discrepancy({expected:3,actual:2}),-1);
assert.equal(m.answers.p2.result,'NOK');
assert.equal(P.discrepancy({expected:'',actual:0}),null);
console.log('PASS protocolos: resultados vacíos, PEND separado, respuesta general, filas ampliables, pendientes sin duplicados y diferencias sin decidir conformidad.');
